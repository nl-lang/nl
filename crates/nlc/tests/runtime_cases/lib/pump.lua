rt.post(function() print("item 1") end)
rt.post(function() error("item 2 fails", 0) end)
rt.post(function() print("item 3") end)
rt.post(function() rt.raise("item 4 raises") end)
rt.post(function() print("item 5"); rt.post(function() print("next pump") end) end)
print("pump", rt.pump())
